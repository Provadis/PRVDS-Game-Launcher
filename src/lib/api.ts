import { invoke } from "@tauri-apps/api/core";
import type {
  ArtKind,
  ArtOption,
  ArtworkKeys,
  Candidate,
  Collection,
  Game,
  GamePatch,
  GameQuery,
  ImportReport,
  InstalledGame,
  LauncherCandidate,
  Platform,
  SavedView,
  Session,
  Settings,
  SyncReport,
  UpdateChannel,
  UpdateCheck,
  ViewDefinition,
} from "./types";

export const api = {
  scanDesktop: () => invoke<Candidate[]>("scan_desktop"),
  importShortcuts: (paths: string[]) => invoke<ImportReport>("import_shortcuts", { paths }),
  scanLaunchers: (platforms: Platform[] = []) => invoke<LauncherCandidate[]>("scan_launchers", { platforms }),
  importLauncherGames: (games: InstalledGame[]) => invoke<Game[]>("import_launcher_games", { games }),
  syncLaunchers: () => invoke<SyncReport>("sync_launchers"),
  listGames: () => invoke<Game[]>("list_games"),
  queryGames: (query: GameQuery) => invoke<number[]>("query_games", { query }),
  getGame: (id: number) => invoke<Game>("get_game", { id }),
  updateGame: (id: number, patch: GamePatch) => invoke<Game>("update_game", { id, patch }),
  launchGame: (id: number) => invoke<Game>("launch_game", { id }),
  runningGames: () => invoke<number[]>("running_games"),
  sessions: (id: number) => invoke<Session[]>("sessions", { id }),
  tidyDesktop: () => invoke<Game[]>("tidy_desktop"),
  removeGame: (id: number) => invoke<void>("remove_game", { id }),
  undoImport: (id: number) => invoke<string>("undo_import", { id }),
  restoreAll: () => invoke<{ restored: number; failed: { path: string; error: string }[] }>("restore_all"),
  listTags: () => invoke<string[]>("list_tags"),
  addTag: (id: number, tag: string) => invoke<Game>("add_tag", { id, tag }),
  removeTag: (id: number, tag: string) => invoke<Game>("remove_tag", { id, tag }),
  listCollections: () => invoke<Collection[]>("list_collections"),
  createCollection: (name: string) => invoke<Collection>("create_collection", { name }),
  renameCollection: (id: number, name: string) => invoke<void>("rename_collection", { id, name }),
  deleteCollection: (id: number) => invoke<void>("delete_collection", { id }),
  setInCollection: (collectionId: number, gameId: number, member: boolean) =>
    invoke<Game>("set_in_collection", { collectionId, gameId, member }),
  listViews: () => invoke<SavedView[]>("list_views"),
  saveView: (id: number | null, name: string, definition: ViewDefinition) =>
    invoke<SavedView>("save_view", { id, name, definition }),
  deleteView: (id: number) => invoke<void>("delete_view", { id }),
  artOptions: (id: number, kind: ArtKind) => invoke<ArtOption[]>("art_options", { id, kind }),
  setArtFromUrl: (id: number, kind: ArtKind, url: string) => invoke<Game>("set_art_from_url", { id, kind, url }),
  setArtFromFile: (id: number, kind: ArtKind, path: string) => invoke<Game>("set_art_from_file", { id, kind, path }),
  refreshMetadata: (id: number) => invoke<Game>("refresh_metadata", { id }),
  getSettings: () => invoke<Settings>("get_settings"),
  saveKeys: (keys: ArtworkKeys) => invoke<void>("save_keys", { keys }),
  checkUpdate: (channel: UpdateChannel) => invoke<UpdateCheck>("check_update", { channel }),
  installUpdate: () => invoke<void>("install_update"),
  openDataFolder: () => invoke<void>("open_data_folder"),
};
